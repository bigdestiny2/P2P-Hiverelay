import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const directory = dirname(fileURLToPath(import.meta.url))
const build = mkdtempSync(join(directory, '.build-'))
const compiler = process.env.CC || 'cc'
try {
  const source = join(directory, 'flags.c')
  const binary = join(build, 'flags')
  execFileSync(compiler, ['-std=c11', '-Wall', '-Wextra', '-Werror', source, '-o', binary], { stdio: 'inherit' })
  const flags = JSON.parse(execFileSync(binary, { encoding: 'utf8' }))
  if (flags.platform !== process.platform || flags.arch !== process.arch) throw new Error('Cross compilation needs target-side execution and qualification')
  const artifact = {
    ...flags,
    sourceSha256: createHash('sha256').update(readFileSync(source)).digest('hex'),
    probeSha256: createHash('sha256').update(readFileSync(binary)).digest('hex'),
    compiler: execFileSync(compiler, ['--version'], { encoding: 'utf8' }).trim()
  }
  const target = flags.platform + '-' + flags.arch
  const artifactPath = join(directory, 'flags-' + target + '.cjs')
  const bytes = '// Generated by build.mjs from target system headers; do not edit.\nmodule.exports = ' + JSON.stringify(artifact, null, 2) + '\n'
  // Rebuilding must not replace a previously reviewed artifact with a different
  // compiler/probe identity. Retain the candidate in evidence for explicit review.
  if (process.argv[2]) {
    mkdirSync(process.argv[2], { recursive: true })
    copyFileSync(binary, join(process.argv[2], 'native-flags-probe-' + target))
    writeFileSync(join(process.argv[2], 'native-flags-provenance-' + target + '.json'), JSON.stringify(artifact, null, 2) + '\n')
    writeFileSync(join(process.argv[2], 'native-flags-candidate-' + target + '.cjs'), bytes)
  }
  try {
    writeFileSync(artifactPath, bytes, { flag: 'wx' })
  } catch (err) {
    if (err.code !== 'EEXIST') throw err
    if (readFileSync(artifactPath, 'utf8') !== bytes) {
      throw new Error('Existing native flag artifact differs; review the candidate before explicitly replacing ' + artifactPath)
    }
  }
  console.log(JSON.stringify(artifact))
} finally {
  rmSync(build, { recursive: true, force: true })
}
