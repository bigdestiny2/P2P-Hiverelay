import { execFileSync } from 'node:child_process'
import { createHash } from 'node:crypto'
import { copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const directory = dirname(fileURLToPath(import.meta.url))
const build = mkdtempSync(join(directory, '.build-'))
const compiler = process.env.CC || 'cc'
try {
  const source = join(directory, 'flags.c')
  const binary = join(build, 'flags')
  execFileSync(compiler, ['-std=c11', '-Wall', '-Wextra', '-Werror', source, '-o', binary], { stdio: 'inherit' })
  const flags = JSON.parse(execFileSync(binary, { encoding: 'utf8' }))
  if (flags.platform !== process.platform || flags.arch !== process.arch) throw new Error('Cross compilation needs target-side execution and qualification')
  const artifact = {
    ...flags,
    sourceSha256: createHash('sha256').update(readFileSync(source)).digest('hex'),
    probeSha256: createHash('sha256').update(readFileSync(binary)).digest('hex'),
    compiler: execFileSync(compiler, ['--version'], { encoding: 'utf8' }).trim()
  }
  writeFileSync(join(directory, 'flags.cjs'), '// Generated by build.mjs from target system headers; do not edit.\nmodule.exports = ' + JSON.stringify(artifact, null, 2) + '\n')
  if (process.argv[2]) {
    mkdirSync(process.argv[2], { recursive: true })
    copyFileSync(binary, join(process.argv[2], 'native-flags-probe'))
    writeFileSync(join(process.argv[2], 'native-flags-provenance.json'), JSON.stringify(artifact, null, 2) + '\n')
  }
  console.log(JSON.stringify(artifact))
} finally {
  rmSync(build, { recursive: true, force: true })
}
